import torch
import torch.nn as nn
import math
import urllib.request

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# Download Shakespeare (about 1MB, free)
url = "https://raw.githubusercontent.com/karpathy/char-rnn/master/data/tinyshakespeare/input.txt"
urllib.request.urlretrieve(url, "shakespeare.txt")

with open("shakespeare.txt", "r") as f:
    text = f.read()

print("Total characters:", len(text))
print("\n--- First 300 characters ---")
print(text[:300])

"""##### 2. Build the character vocabulary (Data Preprocessing)"""

# Find every unique character in the text
characters = sorted(set(text))
VOCAB_SIZE = len(characters)

print("Vocabulary size:", VOCAB_SIZE)
print("The characters:", "".join(characters))

# Two dictionaries: character → number, and number → character
char_to_number = {ch: i for i, ch in enumerate(characters)}
number_to_char = {i: ch for i, ch in enumerate(characters)}

print(char_to_number)

# Two helper functions
def encode(s):
    return [char_to_number[c] for c in s]

def decode(numbers):
    return "".join([number_to_char[n] for n in numbers])

# Test them!
print("\nencode('hello'):", encode("hello"))
print("decode it back: ", decode(encode("hello")))

# Turn the WHOLE text into one long list of numbers
data = torch.tensor(encode(text), dtype=torch.long)
print("\ndata shape:", data.shape)
print("first 20 numbers:", data[:20].tolist())
print("decoded back:    ", repr(decode(data[:20].tolist())))

"""##### 3. Cut the chunks"""

CHUNK_SIZE = 128      # how many characters the model sees at once
BATCH_SIZE = 32       # how many chunks we process together

# Split: 90% for training, 10% for checking
split_point = int(0.9 * len(data))
train_data = data[:split_point]
val_data   = data[split_point:]

print("train characters:", len(train_data))
print("val characters:  ", len(val_data))


def get_batch(which_split):
    d = train_data if which_split == "train" else val_data

    # pick BATCH_SIZE random starting points
    # torch.randint(0-high, (size,))
    starts = torch.randint(len(d) - CHUNK_SIZE - 1, (BATCH_SIZE,))
    print(starts)

    x = torch.stack([d[s     : s + CHUNK_SIZE    ] for s in starts])   # the chunk
    y = torch.stack([d[s + 1 : s + CHUNK_SIZE + 1] for s in starts])   # shifted by 1!

    return x.to(device), y.to(device)


x, y = get_batch("train")
print(f"\n x:- {x}")
print(f"\n y:- {y}")
print("\nx shape:", x.shape)
print("y shape:", y.shape)

